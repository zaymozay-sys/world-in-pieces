if (typeof _t === 'undefined' && typeof require === 'function') require('./i18n.js'); // i18n
/* Почта (1.8.9): письма от жителей деревни и от самой игры. Приходят, когда выполнено условие (первая победа, уровень, медали…);
   к части писем приложен подарок (монеты в «зельях здоровья» P, расходники) — забирается один раз. Письма между игроками — только с сервером.
   Чистый модуль: Profile.data.mail = { box:[{ id, at, read, claimed }] }. Тексты — из каталога LETTERS (по id), в сохранении их нет.
   ctx: { wins, level, battles, medals, pet, trophies, decor, puzzle, dungeon }. */
const Mail = (() => {
  const CAP = 80;
  const L = (id, from, subject, body, when, gift) => ({ id, from, subject, body, when, gift: gift || null });
  const LETTERS = [
    L('welcome', () => _t("Трактирщик"), () => _t("Добро пожаловать в деревню"), () => _t("Заходи в таверну, когда будет время: у меня всегда найдётся поручение. И не забывай про осколки — мир держится на них."), () => true, { p: 2 }),
    L('win1', () => _t("Мельник"), () => _t("С первой победой!"), () => _t("Слышал, ты уже побил первого зверя. Вот гостинец — зелье лишним не будет. Заглядывай на мельницу, смелем зерно."), (c) => c.wins >= 1, { cons: { potion: 1 } }),
    L('win10', () => _t("Трактирщик"), () => _t("Десять побед"), () => _t("В деревне о тебе уже говорят. Угощение за счёт заведения — пара монет на дорожку."), (c) => c.wins >= 10, { p: 3 }),
    L('win50', () => _t("Тюлень-смотритель"), () => _t("Огонь маяка"), () => _t("Пятьдесят побед — береговая нечисть тебя запомнила. Приходи сыграть в «Обвал», жетоны ждут."), (c) => c.wins >= 50, { cons: { scroll: 1 } }),
    L('lvl5', () => _t("Бобёр-библиотекарь"), () => _t("Пятый уровень"), () => _t("Поздравляю! В библиотеке теперь есть свитки и для тебя. Переписка свитков — моё новое дело, спроси в деревне."), (c) => c.level >= 5, { cons: { scroll: 1 } }),
    L('lvl10', () => _t("Журавль-художник"), () => _t("Десятый уровень"), () => _t("Ты мог бы красиво украсить дом: у меня есть краски и рамки. Загляни в Ратушу — там всё про украшения."), (c) => c.level >= 10, { p: 4 }),
    L('lvl20', () => _t("Староста"), () => _t("Двадцатый уровень"), () => _t("Деревня гордится героем. Пусть этот скромный дар поможет в дальних землях."), (c) => c.level >= 20, { p: 8, cons: { elixir: 1 } }),
    L('battles100', () => _t("Мельник"), () => _t("Сто боёв"), () => _t("Сто боёв — и всё ещё на ногах. Лови мешочек муки за стойкость (то есть монеты)."), (c) => c.battles >= 100, { p: 3 }),
    L('medals5', () => _t("Бобёр-библиотекарь"), () => _t("Первые медали"), () => _t("Пять медалей в коллекции! Я записал их в книгу рекордов. Загляни на вкладку «Медали» — она красивая."), (c) => c.medals >= 5, null),
    L('pet', () => _t("Хозяин питомника"), () => _t("Новый друг"), () => _t("Слышал, у тебя теперь питомец. Корми его вовремя — в питомнике есть корм, а промысел «Корм» даёт мёд."), (c) => !!c.pet, { cons: { potion: 1 } }),
    L('rare', () => _t("Журавль-художник"), () => _t("Чучело на память"), () => _t("Редкого зверя одолел — это событие. Повесь трофей на стену: в зале трофеев ему самое место."), (c) => c.trophies >= 1, { p: 6 }),
    L('decor3', () => _t("Мельник"), () => _t("Красиво у тебя"), () => _t("Зашёл мимо — а у тебя в доме уже уютно. Так держать!"), (c) => c.decor >= 3, { p: 2 }),
    L('puzzle7', () => _t("Бобёр-библиотекарь"), () => _t("Любитель головоломок"), () => _t("Семь головоломок дня решено. Могу предложить ещё одну задачу, но завтра."), (c) => c.puzzle >= 7, { cons: { scroll: 2 } }),
    L('dungeon5', () => _t("Тюлень-смотритель"), () => _t("Подземелье"), () => _t("Пятый уровень подземелья пройден. Говорят, внизу ещё страшнее. Береги себя."), (c) => c.dungeon >= 5, { p: 10 }),
  ];
  const BY_ID = Object.fromEntries(LETTERS.map((l) => [l.id, l]));
  function clean(m) {
    m = m && typeof m === 'object' ? m : {};
    const seen = {}, box = [];
    for (const e of Array.isArray(m.box) ? m.box : []) {
      if (!e || !BY_ID[e.id] || seen[e.id]) continue;
      seen[e.id] = 1; box.push({ id: e.id, at: Number.isFinite(e.at) ? e.at : 0, read: !!e.read, claimed: !!e.claimed });
    }
    return { box: box.slice(-CAP) };
  }
  const has = (m, id) => m.box.some((e) => e.id === id);
  // добавляет письма, чьё условие выполнено; возвращает список новых id
  function sync(m, ctx, now) {
    const out = [];
    for (const l of LETTERS) if (!has(m, l.id) && l.when(ctx || {})) { m.box.push({ id: l.id, at: now || 0, read: false, claimed: !l.gift }); out.push(l.id); }
    if (m.box.length > CAP) m.box.splice(0, m.box.length - CAP);
    return out;
  }
  const unread = (m) => m.box.filter((e) => !e.read).length;
  function read(m, id) { const e = m.box.find((x) => x.id === id); if (!e) return false; e.read = true; return true; }
  // подарок письма (один раз): { p, cons } или null
  function claim(m, id) {
    const e = m.box.find((x) => x.id === id), l = BY_ID[id];
    if (!e || !l || !l.gift || e.claimed) return null;
    e.claimed = true; e.read = true; return l.gift;
  }
  return { LETTERS, BY_ID, clean, sync, unread, read, claim, has };
})();
if (typeof module !== 'undefined' && module.exports) module.exports = Mail;
