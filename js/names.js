if (typeof _t === 'undefined' && typeof require === 'function') require('./i18n.js'); // i18n
/* Генератор случайного «звёздного» ника — для тех, кто не может придумать себе имя на экране регистрации
   (см. js/screens.js, faction.html: кнопка рядом с полем ника). Список — вольные, ощутимо фэнтезийные
   имена по мотивам астрономии (звёзды, туманности, созвездия), без названий из чужих научно-фантастических
   вселенных — только небо и никакой конкретной франшизы. Чистая функция без интерфейса — можно тестировать в Node. */

const Names = (() => {
  // Имена/фразы на тему звёзд, туманностей и созвездий — русифицированные или вольно переведённые,
  // подобраны под фэнтезийный тон игры (см. дизайн-документ).
  const STAR_NAMES = [
    _t("Вега"), _t("Альтаир"), _t("Ригель"), _t("Спика"), _t("Арктур"), _t("Бетельгейзе"), _t("Антарес"), _t("Полярная Звезда"),
    _t("Капелла"), _t("Денеб"), _t("Альдебаран"), _t("Сириус"), _t("Процион"), _t("Мицар"), _t("Алькор"), _t("Беллатрикс"),
    _t("Туманность Ориона"), _t("Туманность Андромеды"), _t("Крабовидная Туманность"), _t("Кольцевая Туманность"),
    _t("Туманность Орла"), _t("Туманность Розетка"), _t("Северная Корона"), _t("Южный Крест"), _t("Большая Медведица"),
    _t("Малая Медведица"), _t("Кассиопея"), _t("Плеяды"), _t("Гиады"), _t("Млечный Путь"), _t("Утренняя Звезда"), _t("Вечерняя Звезда"),
    _t("Звёздная Пыль"), _t("Звездопад"), _t("Хвост Кометы"), _t("Свет Далёкой Звезды"), _t("Искра Небосвода"),
    _t("Осколок Кристалла Небес"), _t("Странница Комета"), _t("Полночное Сияние"), _t("Рассветная Звёздочка"),
  ];

  // rand — генератор [0,1) (по умолчанию Math.random, подменяется в тестах).
  function randomStarName(rand = Math.random) {
    return STAR_NAMES[Math.floor(rand() * STAR_NAMES.length)];
  }

  return { STAR_NAMES, randomStarName };
})();

// Для тестов в Node.js (в браузере не используется).
if (typeof module !== 'undefined') module.exports = Names;
