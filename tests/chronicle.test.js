const assert = require('assert');
global._t = (s, a) => (a ? s.replace(/\{(\d+)\}/g, (_, i) => a[i]) : s);
const Chron = require('../js/chronicle.js');
const d = {};
assert.ok(Chron.winMark(d, 1) && Chron.winMark(d, 10) && !Chron.winMark(d, 11));
assert.strictEqual(Chron.winMark(d, 10), null, 'разовая отметка не повторяется');
assert.ok(Chron.add(d, 'level', 5) === null || true);
Chron.levelMarks(d, 12);
assert.deepStrictEqual(d.chron.filter((e) => e.k === 'level').map((e) => e.a), [5, 10]);
Chron.levelMarks(d, 12);
assert.strictEqual(d.chron.filter((e) => e.k === 'level').length, 2);
Chron.add(d, 'pet', 'Волк'); Chron.add(d, 'pet', 'Волк');
assert.strictEqual(d.chron.filter((e) => e.k === 'pet').length, 2, 'питомцы записываются каждый раз');
assert.strictEqual(Chron.add(d, 'nope', 1), null);
assert.strictEqual(Chron.text({ k: 'win', a: 1 }), 'Первая победа в бою.');
assert.strictEqual(Chron.text({ k: 'win', a: 50 }), '50-я победа в боях.');
assert.strictEqual(Chron.list(d)[0].k, 'pet', 'новые сверху');
const big = {}; for (let i = 0; i < 400; i++) Chron.add(big, 'pet', 'x' + i);
assert.strictEqual(big.chron.length, Chron.MAX);
assert.deepStrictEqual(Chron.list({ chron: 'мусор' }), []);
assert.ok(/^\d\d\.\d\d\.\d{4}$/.test(Chron.dateStr(Date.now())));
console.log('chronicle: все тесты пройдены');
